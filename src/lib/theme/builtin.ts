import type { Theme, ThemeVariant } from "./types";

interface Base {
  bg: string;
  fg: string;
  card: string;
  muted: string;
  mutedFg: string;
  accent: string;
  border: string;
  primary: string;
  primaryFg: string;
  destructive: string;
  ring: string;
  /** `input` differs from `border` in some themes. */
  input?: string;
  lanes: string[];
  anonymous: string;
}

/** Fills the tokens that follow from a few base colors. */
function variant(b: Base): ThemeVariant {
  return {
    colors: {
      background: b.bg,
      foreground: b.fg,
      card: b.card,
      "card-foreground": b.fg,
      popover: b.card,
      "popover-foreground": b.fg,
      primary: b.primary,
      "primary-foreground": b.primaryFg,
      secondary: b.muted,
      "secondary-foreground": b.fg,
      muted: b.muted,
      "muted-foreground": b.mutedFg,
      accent: b.accent,
      "accent-foreground": b.fg,
      destructive: b.destructive,
      border: b.border,
      input: b.input ?? b.border,
      ring: b.ring,
    },
    lanes: b.lanes,
    anonymous: b.anonymous,
  };
}

const theme = (id: string, name: string, light: Base, dark: Base): Theme => ({
  id,
  name,
  builtin: true,
  radius: 0.625,
  light: variant(light),
  dark: variant(dark),
});

