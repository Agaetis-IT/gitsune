/** One flavor as a variant of a theme: base for the page, mantle for panels, mauve as accent. */
function catppuccin(f: Flavor): Base {
  return {
    bg: f.base,
    fg: f.text,
    card: f.mantle,
    muted: f.surface0,
    mutedFg: f.subtext0,
    accent: f.surface1,
    border: f.surface1,
    primary: f.mauve,
    primaryFg: f.base,
    destructive: f.red,
    ring: f.mauve,
    lanes: [
      f.red,
      f.peach,
      f.yellow,
      f.green,
      f.teal,
      f.sky,
      f.sapphire,
      f.blue,
      f.lavender,
      f.mauve,
      f.pink,
      f.flamingo,
    ],
    anonymous: f.overlay1,
  };
}

